const char* DFA_S_GetName(int style) {
    if (style < 0 || style >= DFA_STYLE_COUNT) return "未知";
    return kStyleNames[style];
}

const char* DFA_S_GetTag(int style) {
    if (style < 0 || style >= DFA_STYLE_COUNT) return "";
    return kStyleTags[style];
}

const StyleGuide* DFA_S_GetGuide(int style) {
    if (style < 0 || style >= DFA_STYLE_COUNT) return nullptr;
    return &kGuides[style];
}
