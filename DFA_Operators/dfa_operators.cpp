// ---------- 各兵种对五种玩法的加分 ----------
// 列顺序 = DfaStyle：跑刀 / 鼠鼠 / 正常玩 / 微交战 / 全装猛攻
static const int kRoleScore[OP_ROLE_COUNT][DFA_STYLE_COUNT] = {
    /* 支援 */ {  0,  2,  3,  1,  1 },
    /* 工程 */ {  1,  1,  2,  2,  2 },
    /* 侦察 */ {  2,  3,  2,  1,  0 },
    /* 突击 */ {  0,  0,  2,  4,  4 },
};

int DFA_O_GetOperatorCount() {
    return (int)(sizeof(kOperators) / sizeof(kOperators[0]));
}

const OperatorInfo* DFA_O_GetOperator(int idx) {
    if (idx < 0 || idx >= DFA_O_GetOperatorCount()) return nullptr;
    return &kOperators[idx];
}

const char* DFA_O_GetRoleName(DfaRole r) {
    if (r < 0 || r >= OP_ROLE_COUNT) return "未知";
    return kRoleNames[r];
}

const int* DFA_O_GetRoleScores(DfaRole r) {
    static const int kZero[DFA_STYLE_COUNT] = { 0, 0, 0, 0, 0 };
    if (r < 0 || r >= OP_ROLE_COUNT) return kZero;
    return kRoleScore[r];
}
